#!/usr/bin/env node
/**
 * Builds supabase/base_test.sql: EVERY migration, in order, in one file, to create the "LinkPay Test" database in one
 * paste in the Supabase SQL editor (docs/BASE_TEST.md). Run again after adding a migration:
 *
 *   node supabase/construire-base-test.js        (from linkpay-api/)
 *
 * - The database is marked TEST (migration 071 reads linkpay.environment): test money is allowed there, real
 *   payments are refused by the API. Never run base_test.sql on the production project.
 * - The three migrations that exist twice with the same content (033/036, 034/037, 035/038) are taken once.
 * - The Supabase SQL editor runs a pasted script as ONE transaction, and Postgres refuses to use an enum value in the
 *   transaction that added it: a COMMIT follows every "ALTER TYPE … ADD VALUE".
 */
const fs = require('fs');
const path = require('path');

const DIR = path.join(__dirname, 'migrations');
const OUT = path.join(__dirname, 'base_test.sql');
const DUPLICATES = new Set(['033_stock_categories_and_password.sql', '034_sales.sql', '035_sales_history_and_invoice.sql']);

const files = fs.readdirSync(DIR).filter((f) => /^\d{3}_.+\.sql$/.test(f) && !DUPLICATES.has(f)).sort();

const parts = [
  `-- ============================================================================
-- base_test.sql — GENERATED by supabase/construire-base-test.js: do not edit by hand.
--
-- Creates the "LinkPay Test" database from an EMPTY Supabase project, in one paste in the SQL editor.
-- ${files.length} migrations, ${files[0]} to ${files[files.length - 1]}.
--
-- NEVER run this on the production project: it marks the database as TEST for good.
-- ============================================================================

SET linkpay.environment = 'test';
`,
];

for (const f of files) {
  let sql = fs.readFileSync(path.join(DIR, f), 'utf8');
  sql = sql.replace(/^(\s*ALTER TYPE [^;]+ ADD VALUE[^;]*;)[ \t]*$/gim, '$1\nCOMMIT; -- the new enum value must be committed before it is used');
  parts.push(`\n-- ============================================================================\n-- ${f}\n-- ============================================================================\n${sql.trimEnd()}\n`);
}

parts.push(`
-- ============================================================================
-- Done: this must say "test".
-- ============================================================================
SELECT name AS environnement FROM platform_environment;
`);

fs.writeFileSync(OUT, parts.join(''));
console.log(`${path.relative(process.cwd(), OUT)} : ${files.length} migrations (${files[0]} … ${files[files.length - 1]})`);
